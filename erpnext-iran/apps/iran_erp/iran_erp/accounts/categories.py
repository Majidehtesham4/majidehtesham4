def persian_descriptions():
	"""Replace ERPNext's English descriptions of the standard categories, unless someone edited them."""
	if not frappe.db.table_exists("Account Category"):
		return
	for name, (_label, description) in CATEGORIES.items():
		current = frappe.db.get_value("Account Category", name, "description")
		if current and current.isascii():
			frappe.db.set_value("Account Category", name, "description", description, update_modified=False)
